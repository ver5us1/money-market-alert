BEGIN;

DO $$ BEGIN
    CREATE TYPE news_processing_status AS ENUM ('new', 'analyzed', 'rejected', 'low', 'sent', 'error');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN
    CREATE TYPE sentiment_type AS ENUM ('positive', 'negative', 'neutral');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN
    CREATE TYPE importance_type AS ENUM ('low', 'medium', 'high');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN
    CREATE TYPE alert_delivery_status AS ENUM ('pending', 'sent', 'failed');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    telegram_id BIGINT NOT NULL UNIQUE,
    username TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS assets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticker TEXT NOT NULL UNIQUE,
    company_name TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS user_subscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    asset_id BIGINT NOT NULL REFERENCES assets(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (user_id, asset_id)
);
CREATE TABLE IF NOT EXISTS news_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_id BIGINT NOT NULL UNIQUE,
    asset_id BIGINT NOT NULL REFERENCES assets(id),
    source TEXT,
    headline TEXT NOT NULL,
    summary TEXT,
    url TEXT,
    published_at TIMESTAMPTZ NOT NULL,
    received_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    processing_status news_processing_status NOT NULL DEFAULT 'new'
);
CREATE TABLE IF NOT EXISTS news_analysis (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    news_id BIGINT NOT NULL UNIQUE REFERENCES news_items(id),
    is_relevant BOOLEAN NOT NULL,
    sentiment sentiment_type NOT NULL,
    importance importance_type NOT NULL,
    short_summary TEXT NOT NULL,
    reasoning TEXT NOT NULL,
    possible_impact TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    news_id BIGINT NOT NULL REFERENCES news_items(id),
    analysis_id BIGINT NOT NULL REFERENCES news_analysis(id),
    telegram_message TEXT NOT NULL,
    sent_at TIMESTAMPTZ,
    delivery_status alert_delivery_status NOT NULL DEFAULT 'pending',
    UNIQUE (user_id, news_id)
);

CREATE INDEX IF NOT EXISTS news_queue_idx ON news_items (processing_status, published_at DESC);
CREATE INDEX IF NOT EXISTS subscriptions_asset_idx ON user_subscriptions (asset_id, is_active);

